package com.cyclecare.core.domain.prediction

import com.cyclecare.core.model.CycleSource
import java.io.File
import java.time.LocalDate

/**
 * The golden fixtures of spec `12` §7.
 *
 * A golden fixture is a full input and the exact output the engine
 * produced for it, pinned per algorithm version. It is the regression
 * defence: the corpus gates are the design evidence, and the fixtures
 * are what proves the engine has not quietly changed underneath the
 * gates.
 *
 * Two rules from `12` §7 govern them:
 *
 *  1. **Fixtures are generated, then reviewed and committed.** They are
 *     generated by [generate] and then read by a human before they are
 *     committed. Nothing regenerates them automatically, and no test
 *     writes to them.
 *  2. **Any behaviour change requires a version bump and a documented
 *     reason.** Every fixture records the `algorithmVersion` it was
 *     generated under, and the fixture test fails when that version is
 *     not the version the code now produces. A behaviour change without
 *     a bump therefore fails the suite rather than passing quietly.
 */
internal object GoldenFixtures {

    /** Where the fixtures live, under `core/domain/src/test/resources`. */
    const val DIRECTORY = "prediction/v2"

    /** The engine the fixtures were generated with. */
    private val engine = CyclePredictionEngineV2()

    /** One fixture: the input, and where to write it. */
    data class Spec(
        val fileName: String,
        val description: String,
        val today: LocalDate,
        val observed: List<ObservedCycleStart>,
    )

    /**
     * The fixtures `12` §7 names.
     *
     * One per behaviour the engine has to hold: an ordinary history, a
     * dispersed one, a catastrophic outlier, an implausible gap, a
     * history too short to support a range, a drifting history, a
     * history the user has edited, and a history that crosses a leap
     * day.
     *
     * `today` is the last observed start in every case, which is the
     * rolling-origin convention `12` §4 describes: "Every prediction is
     * made with `today` equal to the last observed start, matching real
     * usage."
     */
    fun specs(): List<Spec> = listOf(
        spec(
            fileName = "stable_28_8cycles.json",
            description = "Eight 28-day cycles. The window collapses to the one-day floor.",
            scenario = Corpus.stable(cycles = 8, mean = 28),
        ),
        spec(
            fileName = "regular_28_sigma2_6cycles.json",
            description = "Six cycles around 28 days with two days of spread.",
            scenario = Corpus.regular(cycles = 6, mean = 28, sigma = 2.0),
        ),
        spec(
            fileName = "single_200day_outlier.json",
            description = "One 200-day gap among otherwise ordinary cycles. The gap is excluded, the estimate is not.",
            scenario = Corpus.singleOutlier(cycles = 8, mean = 28, outlier = 200),
        ),
        spec(
            fileName = "impossible_gap_excluded.json",
            description = "A 300-day gap between ordinary cycles. The gap is excluded and reported, not averaged in.",
            scenario = Corpus.impossibleGap(),
        ),
        spec(
            fileName = "insufficient_history_2cycles.json",
            description = "Two cycles. There is no range to give, and the engine must not invent one.",
            scenario = Corpus.stable(cycles = 2, mean = 28),
        ),
        spec(
            fileName = "drifting_up.json",
            description = "Cycles two days longer each time. The drift correction is applied and capped.",
            scenario = Corpus.linearDrift(cycles = 9, startLength = 28, slopePerCycle = 2),
        ),
        spec(
            fileName = "corrected_retroactive_edit.json",
            description = "A recorded start edited three days later. The estimate moves inside the previous window.",
            scenario = Corpus.corrected(Corpus.regular(cycles = 8), 2, 3),
        ),
        spec(
            fileName = "leap_year_boundary.json",
            description = "Twenty-eight-day cycles spanning a year boundary and 29 February 2024.",
            scenario = Corpus.calendarEdge(),
        ),
    )

    private fun spec(
        fileName: String,
        description: String,
        scenario: Corpus.Scenario,
    ): Spec = Spec(
        fileName = fileName,
        description = description,
        today = scenario.starts.last(),
        observed = observed(scenario.starts),
    )

    /**
     * Observed records for a list of starts.
     *
     * Five-day periods, the same convention the gate suite uses, and
     * every record an observed one: the engine filters out records the
     * app itself predicted.
     */
    private fun observed(starts: List<LocalDate>): List<ObservedCycleStart> =
        starts.mapIndexed { index, start ->
            ObservedCycleStart(
                id = "r$index",
                startDate = start,
                endDate = start.plusDays(4),
                source = CycleSource.User,
            )
        }

    /**
     * Generates the fixtures into [targetDirectory].
     *
     * This is a deliberate act: it is not called by any test. It writes
     * to a scratch directory by default so that the committed fixtures
     * can only be replaced by someone who means to.
     */
    fun generate(targetDirectory: File): List<File> {
        targetDirectory.mkdirs()
        return specs().map { spec ->
            val prediction = requireNotNull(
                engine.predict(
                    CyclePredictionInput(
                        observed = spec.observed,
                        userReportedAverageCycleLength = null,
                        today = spec.today,
                    ),
                ),
            )
            val file = File(targetDirectory, spec.fileName)
            file.writeText(MiniJson.write(toJson(spec, prediction)))
            file
        }
    }

    /** Reads a fixture file into its JSON tree. */
    fun read(file: File): Map<String, Any?> {
        @Suppress("UNCHECKED_CAST")
        return MiniJson.parse(file.readText()) as Map<String, Any?>
    }

    private fun toJson(spec: Spec, prediction: CyclePrediction): Map<String, Any?> = linkedMapOf(
        "name" to spec.fileName.removeSuffix(".json"),
        "algorithmVersion" to PREDICTION_ALGORITHM_VERSION,
        "description" to spec.description,
        "today" to spec.today.toString(),
        "observed" to spec.observed.map { record ->
            linkedMapOf(
                "id" to record.id,
                "startDate" to record.startDate.toString(),
                "endDate" to record.endDate?.toString(),
                "source" to record.source.name,
            )
        },
        "expected" to linkedMapOf(
            "nextPeriodDate" to prediction.nextPeriodDate.toString(),
            "nextPeriodWindow" to prediction.nextPeriodWindow?.let { window ->
                linkedMapOf(
                    "start" to window.start.toString(),
                    "endInclusive" to window.endInclusive.toString(),
                    "halfWidthDays" to window.halfWidthDays,
                )
            },
            "fertileWindow" to prediction.fertileWindow?.let { window ->
                linkedMapOf(
                    "start" to window.start.toString(),
                    "endInclusive" to window.endInclusive.toString(),
                    "halfWidthDays" to window.halfWidthDays,
                )
            },
            "ovulationDate" to prediction.ovulationDate.toString(),
            "centerCycleLength" to prediction.centerCycleLength,
            "dispersionSigma" to prediction.dispersionSigma,
            "trendAdjustmentDays" to prediction.trendAdjustmentDays,
            "isIrregular" to prediction.isIrregular,
            "isStale" to prediction.isStale,
            "quality" to prediction.quality.name,
            "warnings" to prediction.warnings.map { it.name },
            "recordIdsUsed" to prediction.recordIdsUsed,
            "intervalsUsed" to prediction.intervalsUsed.map { interval ->
                linkedMapOf(
                    "fromRecordId" to interval.fromRecordId,
                    "toRecordId" to interval.toRecordId,
                    "startDate" to interval.startDate.toString(),
                    "lengthDays" to interval.lengthDays,
                    "usable" to interval.usable,
                    "exclusionReason" to interval.exclusionReason,
                )
            },
            "intervalsExcluded" to prediction.intervalsExcluded.map { interval ->
                linkedMapOf(
                    "fromRecordId" to interval.fromRecordId,
                    "toRecordId" to interval.toRecordId,
                    "startDate" to interval.startDate.toString(),
                    "lengthDays" to interval.lengthDays,
                    "usable" to interval.usable,
                    "exclusionReason" to interval.exclusionReason,
                )
            },
        ),
    )
}
